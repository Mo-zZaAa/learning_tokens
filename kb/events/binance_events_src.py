def fmap():
    m = {}
    p = os.path.join(os.path.dirname(__file__), '..', '..', 'db', '_fact_id_map.csv')
    for line in open(p, encoding='utf-8').read().split('\n')[1:]:
        c = line.split(',')
        if len(c) >= 3:
            m[c[2].strip()] = c[0].strip()
    return m


