HL = set()
NEW = {}


def walk(items):
    for it in items:
        yield it
        yield from walk(it.get("kids") or [])
        yield from walk(it.get("sub") or [])


def all_items():
    for r in d["card"]["rows"]:
        yield from walk(r.get("items") or [])
        yield from walk(r.get("path") or [])


def find(prefix):
    hits = [it for it in all_items() if (it.get("t") or "").startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]


def hl(it, phrase, m="=="):
    t = it["t"]
    assert t.count(phrase) == 1, (phrase, t[:50])
    it["t"] = t.replace(phrase, m + phrase + m)
    HL.add(id(it))


def red(it, phrase):
    hl(it, phrase, "!!")


def add(it, place, t, kids=None, pos=None):
    k = {"t": t}
    if kids:
        k["kids"] = [{"t": x} for x in kids]
    it.setdefault("kids", [])
    if pos is None:
        it["kids"].append(k)
    else:
        it["kids"].insert(pos, k)
    NEW[place] = NEW.get(place, 0) + 1 + len(kids or [])


