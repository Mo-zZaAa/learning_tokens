def main():
    d = json.loads(P.read_text(encoding="utf-8"))
    rows = [r for r in d["card"]["rows"] if r.get("label") != "핵심 포인트"]
    rows.insert(0, {"label": "핵심 포인트", "hot": True, "items": POINTS})
    d["card"]["rows"] = rows
    P.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    n_go = sum(1 for p in POINTS if p.get("go")) + sum(1 for p in POINTS for x in p["kids"] if x.get("go"))
    print(f"핵심 포인트 {len(POINTS)}개, 꼬리 {sum(len(p['kids']) for p in POINTS)}개, 이동 버튼 {n_go}")


if __name__ == "__main__":
    main()
