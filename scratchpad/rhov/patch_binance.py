"""Binance 1층 카드: 질문(kb/coverage/binance.csv, kb/pm_q2/binance.md, 녹취 Binance 행)에 맞춰 강조, 보강, 정정."""
import json
P = "kb/binance_overview/binance_overview.json"
d = json.load(open(P, encoding="utf-8"))
rows = {r["label"]: r for r in d["card"]["rows"]}
HL = set()
NEW = {}
FIX = []


def walk(items):
    for it in items:
        yield it
        yield from walk(it.get("kids") or [])
        yield from walk(it.get("sub") or [])


def all_items():
    for r in d["card"]["rows"]:
        if r["label"] in ("한눈에 보기", "먼저 볼 질문") or r.get("hot"):
            continue
        yield from walk(r.get("items") or [])
        yield from walk(r.get("path") or [])


def find(prefix):
    hits = [it for it in all_items() if (it.get("t") or "").startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]


def pathk(k):
    hits = [p for p in rows["확장 경로"]["path"] if p.get("k") == k]
    assert len(hits) == 1, k
    return hits[0]


def kid(t, kids=None):
    o = {"t": t}
    if kids:
        o["kids"] = [{"t": x} for x in kids]
    return o


def hl(it, phrase, m="=="):
    if isinstance(it, str):
        it = find(it)
    t = it["t"]
    assert t.count(phrase) == 1, (phrase, t[:60])
    it["t"] = t.replace(phrase, m + phrase + m)
    HL.add((id(it), phrase))


def red(it, phrase):
    hl(it, phrase, "!!")


def tcell(it, key, col, phrase, m="==", keycol=0):
    if isinstance(it, str):
        it = find(it)
    rs = [r for r in it["table"]["rows"] if r[keycol].startswith(key)]
    assert len(rs) == 1, (key, len(rs))
    c = rs[0][col]
    assert c.count(phrase) == 1, (key, col, phrase)
    rs[0][col] = c.replace(phrase, m + phrase + m)
    HL.add((id(it), key, col, phrase))


def add(where, target, line, at=None):
    target.setdefault("kids", [])
    if at is None:
        target["kids"].append(line)
    else:
        target["kids"].insert(at, line)
    NEW[where] = NEW.get(where, 0) + 1 + len(line.get("kids") or [])


def fix(it, old, new):
    t = it["t"]
    assert t.count(old) == 1, (old, t[:60])
    it["t"] = t.replace(old, new)
    FIX.append((old, new))


def fixcell(it, key, col, old, new, keycol=0):
    rs = [r for r in it["table"]["rows"] if r[keycol].startswith(key)]
    assert len(rs) == 1, key
    assert rs[0][col].count(old) == 1, (key, col, old)
    rs[0][col] = rs[0][col].replace(old, new)
    FIX.append((f"[{key} 칸] {old}", new))


