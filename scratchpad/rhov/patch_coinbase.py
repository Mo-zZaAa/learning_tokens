import json
P = "kb/coinbase_overview/coinbase_overview.json"
d = json.load(open(P, encoding="utf-8"))
rows = {r["label"]: r for r in d["card"]["rows"]}
HL = set()
NEW = {}

def walk(items):
    for it in items:
        yield it
        yield from walk(it.get("kids") or [])
        yield from walk(it.get("sub") or [])
def all_items():
    for r in d["card"]["rows"]:
        yield from walk(r.get("items") or [])
        yield from walk(r.get("path") or [])
def find(prefix):
    hits = [it for it in all_items() if (it.get("t") or "").startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]
def pathk(k):
    hits = [p for p in rows["확장 경로"]["path"] if p.get("k") == k]
    assert len(hits) == 1, k
    return hits[0]
def kid(t, kids=None):
    o = {"t": t}
    if kids: o["kids"] = [{"t": x} for x in kids]
    return o
def hl(prefix, phrase, m="=="):
    it = find(prefix); t = it["t"]
    assert t.count(phrase) == 1, (prefix, phrase)
    it["t"] = t.replace(phrase, m + phrase + m)
    HL.add(id(it))
def red(prefix, phrase): hl(prefix, phrase, "!!")
def tcell(prefix, key, col, phrase, m="==", keycol=0):
    it = find(prefix)
    rs = [r for r in it["table"]["rows"] if r[keycol].startswith(key)]
    assert len(rs) == 1, (prefix, key)
    c = rs[0][col]; assert c.count(phrase) == 1, (key, col, phrase)
    rs[0][col] = c.replace(phrase, m + phrase + m)
    HL.add((prefix, key, col))
def add(where, target, line, at=None):
    target.setdefault("kids", [])
    if at is None: target["kids"].append(line)
    else: target["kids"].insert(at, line)
    NEW[where] = NEW.get(where, 0) + 1 + len(line.get("kids") or [])

